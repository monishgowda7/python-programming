class point:
    
    def __init__(self,x,y):
        self.x=x
        self.y=y
        
    def __add__(self,anself):
        return point((self.x+anself.x),(self.y+anself.y)) 
           
    def __sub__(self,anself):
        return point((self.x-anself.x),(self.y-anself.y))  
    
    def __str__(self):
        return f'{self.x},{self.y}'  
        

