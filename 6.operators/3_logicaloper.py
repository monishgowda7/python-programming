# Logical and Operators(both should be true)
print(True and True)
print(True and False)
print(False and True)
print(False and False)


print("For Or Operator...")#either one should be true
print(True or True)
print(True or False)
print(False or True)
print(False or False)

print("Not Operator...")#reverse the answer
print(not(True)) 
print(not(False)) 